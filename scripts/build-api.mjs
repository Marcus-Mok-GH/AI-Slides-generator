/**
 * Bundle the API into a single CommonJS file for Vercel.
 *
 * `packages: 'external'` keeps node_modules as plain require() calls, so
 * Vercel's file tracing still decides which dependencies ship with the
 * function — we only collapse our own modules, which is what removes the
 * ESM/CommonJS ambiguity at runtime.
 */
import { build } from 'esbuild'

await build({
  entryPoints: ['serverless/entry.js'],
  outfile: 'api/index.js',
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node20',
  packages: 'external',
  logLevel: 'info',
  banner: { js: '// Generated by scripts/build-api.mjs from serverless/entry.js — do not edit.' },
  footer: { js: 'module.exports = module.exports.default || module.exports;' },
})
